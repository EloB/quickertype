#!/usr/bin/env node
// Generates crates/quicktype-js-compat/src/unicode_table.rs from the npm
// package `unicode-properties` 1.4.1, exactly as quicktype-core resolves it.
//
// usage: node xtask/js-compat/gen-unicode.mjs [path/to/quicktype]
//
// The default reference checkout is $QUICKTYPE_DIR, else ../quicktype next to
// this repository. The table maps every code point 0..=0x10FFFF to the
// general category `getCategory` returns, as sorted runs.

import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const quicktypeDir = resolve(
    process.argv[2] ?? process.env.QUICKTYPE_DIR ?? join(repoRoot, "..", "quicktype"),
);
const coreRequire = createRequire(join(quicktypeDir, "packages/quicktype-core/dist/index.js"));
const unicodePath = coreRequire.resolve("unicode-properties");
const unicode = coreRequire("unicode-properties");
const pkg = coreRequire(join(dirname(unicodePath), "..", "package.json"));
if (pkg.version !== "1.4.1") {
    throw new Error(`expected unicode-properties 1.4.1, found ${pkg.version} at ${unicodePath}`);
}

// The category names in the order of the Rust enum (the package's own order).
const CATEGORIES = [
    "Cc", "Zs", "Po", "Sc", "Ps", "Pe", "Sm", "Pd", "Nd", "Lu", "Sk", "Pc", "Ll", "So", "Lo",
    "Pi", "Cf", "No", "Pf", "Lt", "Lm", "Mn", "Me", "Mc", "Nl", "Zl", "Zp", "Cs", "Co",
];

// Out-of-range code points must fall back to "Cc"; the Rust side relies on it.
for (const cp of [-1, 0x110000, 0xffffffff, NaN]) {
    if (unicode.getCategory(cp) !== "Cc") {
        throw new Error(`getCategory(${cp}) is ${unicode.getCategory(cp)}, expected Cc`);
    }
}

const runs = [];
let previous;
for (let cp = 0; cp <= 0x10ffff; cp++) {
    const category = unicode.getCategory(cp);
    if (!CATEGORIES.includes(category)) {
        throw new Error(`unknown category ${category} at U+${cp.toString(16)}`);
    }
    if (category !== previous) {
        runs.push([cp, category]);
        previous = category;
    }
}

const hex = (cp) => `0x${cp.toString(16).toUpperCase().padStart(4, "0")}`;
const perLine = 6;
const lines = [];
for (let i = 0; i < runs.length; i += perLine) {
    lines.push(
        "    " +
            runs
                .slice(i, i + perLine)
                .map(([cp, c]) => `(${hex(cp)}, ${c}),`)
                .join(" "),
    );
}

const out = `// @generated by xtask/js-compat/gen-unicode.mjs from the npm package
// unicode-properties ${pkg.version} (Unicode 12.0 data). Do not edit by hand.
//
// Each entry starts a run of code points that share one general category; a
// run lasts until the next entry's start. The last run extends to U+10FFFF.

use crate::unicode::GeneralCategory::{self, *};

/// Number of category runs in [\`CATEGORY_RUNS\`].
pub(crate) const CATEGORY_RUN_COUNT: usize = ${runs.length};

/// \`(first code point, category)\` for every run, sorted by code point.
#[rustfmt::skip]
pub(crate) static CATEGORY_RUNS: [(u32, GeneralCategory); CATEGORY_RUN_COUNT] = [
${lines.join("\n")}
];
`;

const target = join(repoRoot, "crates/quicktype-js-compat/src/unicode_table.rs");
writeFileSync(target, out);
console.log(`wrote ${runs.length} runs to ${target}`);
