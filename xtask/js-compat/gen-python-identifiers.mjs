#!/usr/bin/env node
// Generates crates/quicktype-core/src/language/python/identifier_table.rs:
// the results of the Python renderer's `isStartCharacter3` and
// `isPartCharacter3` (packages/quicktype-core/src/language/Python/utils.ts)
// for every UTF-16 code unit.
//
// usage: node xtask/js-compat/gen-python-identifiers.mjs [path/to/quicktype]
//
// Both predicates normalize the unit with JavaScript's
// `String.prototype.normalize("NFKC")` (the ICU data of the running Node,
// which must be the Node version tests/golden/REFERENCE records) and classify the
// result with the npm package `unicode-properties` 1.4.1, exactly as
// quicktype-core resolves it. Rust has neither, so the port looks the answers
// up in this table. The functions below are copies of the TypeScript ones.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { referenceCheckout } from "../reference.mjs";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");

// NFKC follows the running Node's ICU data: only the reference's Node gives
// the reference's answers.
const reference = readFileSync(join(repoRoot, "tests/golden/REFERENCE"), "utf8");
const referenceNode = /^node=(.*)$/m.exec(reference)?.[1]?.trim();
if (referenceNode === undefined) {
    throw new Error("tests/golden/REFERENCE records no node= version");
}
if (process.version !== referenceNode) {
    throw new Error(`run with Node ${referenceNode} (tests/golden/REFERENCE), not ${process.version}`);
}
const quicktypeDir = referenceCheckout(process.argv[2]);
const coreRequire = createRequire(join(quicktypeDir, "packages/quicktype-core/dist/index.js"));
const unicodePath = coreRequire.resolve("unicode-properties");
const unicode = coreRequire("unicode-properties");
const pkg = coreRequire(join(dirname(unicodePath), "..", "package.json"));
if (pkg.version !== "1.4.1") {
    throw new Error(`expected unicode-properties 1.4.1, found ${pkg.version} at ${unicodePath}`);
}

function isNormalizedStartCharacter3(utf16Unit) {
    const category = unicode.getCategory(utf16Unit);
    return ["Lu", "Ll", "Lt", "Lm", "Lo", "Nl"].includes(category);
}

function isNormalizedPartCharacter3(utf16Unit) {
    if (isNormalizedStartCharacter3(utf16Unit)) return true;
    const category = unicode.getCategory(utf16Unit);
    return ["Mn", "Mc", "Nd", "Pc"].includes(category);
}

function isStartCharacter3(utf16Unit) {
    const s = String.fromCharCode(utf16Unit).normalize("NFKC");
    const l = s.length;
    if (l === 0 || !isNormalizedStartCharacter3(s.charCodeAt(0))) return false;
    for (let i = 1; i < l; i++) {
        if (!isNormalizedPartCharacter3(s.charCodeAt(i))) return false;
    }

    return true;
}

function isPartCharacter3(utf16Unit) {
    const s = String.fromCharCode(utf16Unit).normalize("NFKC");
    const l = s.length;
    for (let i = 0; i < l; i++) {
        if (!isNormalizedPartCharacter3(s.charCodeAt(i))) return false;
    }

    return true;
}

// Runs of units with the same pair of answers; bit 0 is "start", bit 1 "part".
const runs = [];
let previous;
for (let unit = 0; unit <= 0xffff; unit++) {
    const flags = (isStartCharacter3(unit) ? 1 : 0) | (isPartCharacter3(unit) ? 2 : 0);
    if (flags !== previous) {
        runs.push([unit, flags]);
        previous = flags;
    }
}

const hex = (u) => `0x${u.toString(16).toUpperCase().padStart(4, "0")}`;
const perLine = 8;
const lines = [];
for (let i = 0; i < runs.length; i += perLine) {
    lines.push(
        "    " +
            runs
                .slice(i, i + perLine)
                .map(([u, f]) => `(${hex(u)}, ${f}),`)
                .join(" "),
    );
}

const out = `// @generated by xtask/js-compat/gen-python-identifiers.mjs (Node ${process.version},
// unicode-properties ${pkg.version}). Do not edit by hand.
//
// \`isStartCharacter3\` (bit 0) and \`isPartCharacter3\` (bit 1) of
// Python/utils.ts for every UTF-16 code unit. Each entry starts a run of
// units with the same flags; a run lasts until the next entry's start, the
// last one to U+FFFF.

/// Number of runs in [\`IDENTIFIER_RUNS\`].
pub(crate) const IDENTIFIER_RUN_COUNT: usize = ${runs.length};

/// \`(first unit, flags)\` for every run, sorted by unit.
#[rustfmt::skip]
pub(crate) static IDENTIFIER_RUNS: [(u16, u8); IDENTIFIER_RUN_COUNT] = [
${lines.join("\n")}
];
`;

const target = join(repoRoot, "crates/quicktype-core/src/language/python/identifier_table.rs");
writeFileSync(target, out);
console.log(`wrote ${runs.length} runs to ${target}`);
