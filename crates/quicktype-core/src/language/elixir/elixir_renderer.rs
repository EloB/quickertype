/// The values of `elixirOptions`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ElixirOptions {
    /// `justTypes`.
    pub just_types: bool,
    /// `namespace`.
    pub namespace: String,
}

impl ElixirOptions {
    /// `getOptionValues(elixirOptions, values)`.
    pub fn parse(values: &RendererOptions) -> Result<Self> {
        Ok(ElixirOptions {
            just_types: JUST_TYPES.get_value(values),
            namespace: NAMESPACE.get_value(values).into_owned(),
        })
    }
}

/// `ElixirRenderer`.
pub struct ElixirRenderer<'a> {
    core: ConvenienceRendererCore<'a>,
    options: ElixirOptions,
    /// `_definedClasses`: the classes whose `defstruct` has been emitted.
    defined_classes: IndexSet<TypeRef>,
}

impl std::fmt::Debug for ElixirRenderer<'_> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("ElixirRenderer")
            .field("options", &self.options)
            .finish_non_exhaustive()
    }
}

