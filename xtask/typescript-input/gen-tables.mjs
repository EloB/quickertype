#!/usr/bin/env node
// Generates crates/quicktype-typescript-input/src/tsc/generated.rs from the
// pinned TypeScript 7 package: enum values, the binary-AST child-property
// table and the protocol version. The tsc API is unversioned, so these
// tables are only valid for exactly this TypeScript release.
//
// Usage: node xtask/typescript-input/gen-tables.mjs <quicktype checkout>
// (the checkout's node_modules must contain typescript@7.0.2).

import * as fs from "node:fs";
import * as path from "node:path";
import { pathToFileURL } from "node:url";

import { referenceCheckout } from "../reference.mjs";

const here = path.dirname(new URL(import.meta.url).pathname);
const checkout = referenceCheckout(process.argv[2]);
const ts = path.join(checkout, "node_modules", "typescript");
const pkg = JSON.parse(fs.readFileSync(path.join(ts, "package.json"), "utf8"));
const load = (p) => import(pathToFileURL(path.join(ts, "dist", p)).href);

const enums = [
    ["syntax_kind", "SyntaxKind", "syntaxKind"],
    ["type_flags", "TypeFlags", "typeFlags"],
    ["object_flags", "ObjectFlags", "objectFlags"],
    ["symbol_flags", "SymbolFlags", "symbolFlags"],
    ["element_flags", "ElementFlags", "elementFlags"],
    ["node_flags", "NodeFlags", "nodeFlags"],
    ["modifier_flags", "ModifierFlags", "modifierFlags"],
    ["diagnostic_category", "DiagnosticCategory", "diagnosticCategory"],
];

let out = `// @generated by xtask/typescript-input/gen-tables.mjs from typescript@${pkg.version}.
// Do not edit; regenerate when the pinned TypeScript version changes.
//! Tables generated from the pinned TypeScript 7 package (\`dist/enums\`,
//! \`dist/api/node/protocol*.js\`).
#![allow(non_upper_case_globals, dead_code, clippy::unreadable_literal)]

/// The only TypeScript release whose \`tsc --api\` protocol these tables match.
pub const TSC_VERSION: &str = ${JSON.stringify(pkg.version)};
`;
const proto = await load("api/node/protocol.js");
out += `/// Binary AST protocol version (\`PROTOCOL_VERSION\` in \`protocol.js\`).\npub const PROTOCOL_VERSION: u32 = ${proto.PROTOCOL_VERSION};\n`;

for (const [mod, name, file] of enums) {
    const m = await load(`enums/${file}.enum.js`);
    const e = m[name];
    out += `\n/// \`${name}\` values of typescript@${pkg.version}.\npub mod ${mod} {\n`;
    for (const [k, v] of Object.entries(e)) {
        if (typeof v !== "number") continue;
        out += `    pub const ${k}: u32 = ${v >>> 0};\n`;
    }
    out += "}\n";
}

const sk = (await load("enums/syntaxKind.enum.js")).SyntaxKind;
out += `\n/// Named children of each node kind in binary-AST order (\`childProperties\`).\npub fn child_properties(kind: u32) -> &'static [&'static str] {\n    match kind {\n`;
const entries = Object.entries(proto.childProperties).map(([k, v]) => [Number(k), v]).sort((a, b) => a[0] - b[0]);
for (const [k, props] of entries) {
    out += `        ${k} => &[${props.map((p) => JSON.stringify(p)).join(", ")}], // ${sk[k]}\n`;
}
out += "        _ => &[],\n    }\n}\n";

const target = path.join(here, "../../crates/quicktype-typescript-input/src/tsc/generated.rs");
fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(process.cwd(), target)} (typescript@${pkg.version})`);
