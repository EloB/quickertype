// Generates crates/quicktype-core/src/support/chance_data.rs from the
// reference quicktype's packages/quicktype-core/src/support/Chance.ts.
//
// Usage: node xtask/core-type-graph/gen-chance-data.mjs ../quicktype
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const quicktype = process.argv[2] ?? "../quicktype";
const source = readFileSync(
    join(quicktype, "packages/quicktype-core/src/support/Chance.ts"),
    "utf8",
);

function extract(startMarker, open, close) {
    const start = source.indexOf(startMarker);
    if (start < 0) throw new Error(`missing ${startMarker}`);
    const from = source.indexOf(open, start + startMarker.length - 1);
    let depth = 0;
    for (let i = from; i < source.length; i++) {
        if (source[i] === open) depth++;
        if (source[i] === close) depth--;
        if (depth === 0) return source.slice(from, i + 1);
    }
    throw new Error(`unterminated ${startMarker}`);
}

const animals = new Function(
    `return ${extract("const animals: { [kind: string]: string[] } = {", "{", "}")};`,
)();
const cities = new Function(`return ${extract("const cities: string[] = [", "[", "]")};`)();
const animalTypes = new Function(
    `return ${extract("const animalTypeArray = [", "[", "]")};`,
)();

const lit = (s) => JSON.stringify(s);
const list = (name, items) =>
    `pub(super) static ${name}: &[&str] = &[\n${items.map((s) => `    ${lit(s)},\n`).join("")}];\n`;

let out = "";
out += "// @generated by xtask/core-type-graph/gen-chance-data.mjs from quicktype's\n";
out += "// packages/quicktype-core/src/support/Chance.ts. Do not edit.\n\n";
out += "/// `animalTypeArray` in `Chance.animal()`, in source order.\n";
out += `pub(super) static ANIMAL_TYPES: &[&str] = &[${animalTypes.map(lit).join(", ")}];\n\n`;
out += "/// The `animals` lists, keyed by animal type.\n";
out += "pub(super) fn animals(kind: &str) -> &'static [&'static str] {\n    match kind {\n";
for (const kind of Object.keys(animals)) {
    out += `        ${lit(kind)} => ANIMALS_${kind.toUpperCase()},\n`;
}
out += "        _ => &[],\n    }\n}\n\n";
for (const [kind, items] of Object.entries(animals)) {
    out += list(`ANIMALS_${kind.toUpperCase()}`, items) + "\n";
}
out += "/// `cities`, in source order.\n";
out += list("CITIES", cities);

const target = join(
    dirname(fileURLToPath(import.meta.url)),
    "../../crates/quicktype-core/src/support/chance_data.rs",
);
writeFileSync(target, out);
console.log(`wrote ${target}`);
