{
    if (self = [super init]) {
        [self setValuesForKeysWithDictionary:dict];
        _config = [QTConfig fromJSONDictionary:(id)_config];
        if (!_config && dict[@"config"] && ![dict[@"config"] isKindOfClass:NSNull.class]) return nil;
    }
    return self;
}

