{
    id dict = [[self dictionaryWithValuesForKeys:QTStateState.properties.allValues] mutableCopy];

    for (id jsonName in QTStateState.properties) {
        id propertyName = QTStateState.properties[jsonName];
        if (![jsonName isEqualToString:propertyName]) {
            dict[jsonName] = dict[propertyName];
            [dict removeObjectForKey:propertyName];
        }
    }

