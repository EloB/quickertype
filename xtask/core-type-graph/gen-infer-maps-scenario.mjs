// Generates crates/quicktype-core/tests/fixtures/core-type-graph/scenarios/
// 40-infer-maps-threshold.txt: classes whose property names put InferMaps'
// Markov probability within 15% of its limit, so the class-or-map decision
// depends on exact `evaluate` and `pow` arithmetic. Deterministic (seeded
// mulberry32), so regenerating gives the same file.
//
// Usage: node xtask/core-type-graph/gen-infer-maps-scenario.mjs ../quicktype \
//            > crates/quicktype-core/tests/fixtures/core-type-graph/scenarios/40-infer-maps-threshold.txt
import { createRequire } from "node:module";
import { join, resolve } from "node:path";
const quicktype = resolve(process.argv[2]);
const require = createRequire(join(quicktype, "package.json"));
const { load, evaluate } = require(join(quicktype, "packages/quicktype-core/dist/MarkovChain.js"));
const mc = load();
let seed = 12345;
// mulberry32
const rnd = () => {
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const words = ["name","age","city","value","id","type","data","items","count","status","user","email","phone","address","street","zip","country","created","updated","title","body","tags","price","amount","total","currency","enabled","visible","color","width","height","url","image","thumb","owner","group","level","score","rank","index"];
const alpha = "abcdefghijklmnopqrstuvwxyz";
const exotic = ["café","naïve","中文","日本語","emoji😀","Ωmega","straße"];
function randomName() {
  const r = rnd();
  if (r < 0.35) return words[Math.floor(rnd() * words.length)] + (rnd() < 0.3 ? Math.floor(rnd()*100) : "");
  if (r < 0.75) { let n = 3 + Math.floor(rnd() * 8), s = ""; for (let i = 0; i < n; i++) s += alpha[Math.floor(rnd()*26)]; return s; }
  if (r < 0.9) { let s = ""; for (let i = 0; i < 8; i++) s += "0123456789abcdef"[Math.floor(rnd()*16)]; return s; }
  return exotic[Math.floor(rnd() * exotic.length)] + alpha[Math.floor(rnd()*26)];
}
function limit(n) { const e = 5, s = 22 ** e; return (n + 2) ** e / s + (0.0025 - 3 ** e / s); }
const classes = [];
let attempts = 0;
while (classes.length < 120 && attempts < 200000) {
  attempts++;
  const n = 2 + Math.floor(rnd() * 18);
  const names = new Set();
  while (names.size < n) names.add(randomName());
  const arr = Array.from(names);
  const p = arr.map((x) => evaluate(mc, x)).reduce((a, b) => a * b, 1) ** (1 / n);
  const ratio = p / limit(n);
  // Keep classes close to the threshold, on both sides.
  if (ratio > 0.85 && ratio < 1.15) classes.push(arr);
}
const lines = [
  "# Generated by xtask/core-type-graph/gen-infer-maps-scenario.mjs: classes whose Markov name probability is",
  "# close to InferMaps' limit for their number of properties, so the",
  "# class-or-map decision depends on exact pow/evaluate arithmetic.",
  "builder",
  "prim i integer",
];
const props = [];
classes.forEach((names, k) => {
  lines.push(`ucls c${k} open ${names.map((n) => `${n}:i`).join(",")} n=C${k}`);
  props.push(`p${k}:c${k}`);
});
lines.push(`cls top ${props.join(",")} n=Top`, "top Top top", "finish", "infermaps", "print");
console.log(lines.join("\n"));
