/// `isValidAtom(str)`: whether `str` can be written as a bare atom, checked
/// per UTF-16 code unit.
fn is_valid_atom(s: &str) -> bool {
    let units: Vec<u16> = s.encode_utf16().collect();
    let is_letter = |u: u16| u == u16::from(b'_') || (u < 128 && (u as u8).is_ascii_alphabetic());
    let is_letter_or_digit = |u: u16| is_letter(u) || (u < 128 && (u as u8).is_ascii_digit());

    let Some(&first) = units.first() else {
        return false;
    };
    if !is_letter(first) {
        return false;
    }

    let last = units.len() - 1;
    for (i, &u) in units.iter().enumerate().skip(1) {
        if !is_letter_or_digit(u)
            && u != u16::from(b'@')
            && !(i == last && (u == u16::from(b'!') || u == u16::from(b'?')))
        {
            return false;
        }
    }
    true
}

/// Where a type sorts in `sortAndFilterPatternMatchTypes`: classes, then
/// booleans, enums, other primitives and everything else.
fn pattern_match_rank(kind: TypeKind) -> u8 {
    match kind {
        TypeKind::Class => 0,
        TypeKind::Bool => 1,
        TypeKind::Enum => 2,
        k if k.is_primitive_type_kind() => 3,
        _ => 4,
    }
}

impl<'a> ElixirRenderer<'a> {
    /// `new ElixirRenderer(targetLanguage, renderContext, options)`.
    pub fn new(
        target_language: &'a dyn TargetLanguage,
        render_context: RenderContext<'a>,
        options: ElixirOptions,
    ) -> Self {
        ElixirRenderer {
            core: ConvenienceRendererCore::new(target_language, render_context),
            options,
            defined_classes: IndexSet::new(),
        }
    }

    /// `nameForNamedTypeWithNamespace(t)`.
    fn name_for_named_type_with_namespace(&self, t: TypeRef) -> Result<Source> {
        let name = self.name_for_named_type(t)?;
        Ok(self.name_with_namespace(name))
    }

    /// `nameWithNamespace(n)`.
    fn name_with_namespace(&self, n: Name) -> Source {
        if self.options.namespace.is_empty() {
            sl![n]
        } else {
            sl![self.options.namespace.clone(), ".", n]
        }
    }

    /// `elixirType(t, isOptional)`: the typespec of `t`.
    fn elixir_type(&self, t: TypeRef, is_optional: bool) -> Result<Source> {
        // Endless on a cycle through a nullable union (V8 overflows its stack).
        guard(|| {
            let graph = self.type_graph();
            let optional = if is_optional { " | nil" } else { "" };
            let ty = graph.type_at(t)?;
            Ok(match ty.kind() {
                TypeKind::Any => sl!["any()", optional],
                TypeKind::Null => sl!["nil"],
                TypeKind::Bool => sl!["boolean()", optional],
                TypeKind::Integer => sl!["integer()", optional],
                TypeKind::Double => sl!["float()", optional],
                TypeKind::String => sl!["String.t()", optional],
                TypeKind::Array => sl!["[", self.elixir_type(ty.items()?, false)?, "]", optional],
                TypeKind::Class | TypeKind::Enum => {
                    sl![
                        self.name_for_named_type_with_namespace(t)?,
                        ".t()",
                        optional
                    ]
                }
                TypeKind::Map => sl![
                    "%{String.t() => ",
                    self.elixir_type(ty.map_values()?, false)?,
                    "}",
                    optional
                ],
                TypeKind::Union => {
                    let children: Vec<TypeRef> = graph.children(t)?.into_iter().collect();
                    let mut parts: Vec<Source> = Vec::with_capacity(children.len() * 2);
                    for (index, &child) in children.iter().enumerate() {
                        let element = self.elixir_type(child, false)?;
                        // `flatMap`: the element's own parts are spliced in.
                        match element {
                            Source::Sequence(items) => parts.extend(items),
                            other => parts.push(other),
                        }
                        if index != children.len() - 1 {
                            parts.push(" | ".into());
                        }
                    }
                    sl![Source::Sequence(parts), optional]
                }
                kind => return match_type_unsupported(kind),
            })
        })
    }

    /// `patternMatchClauseDecode(t, attributeName, suffix)`: the
    /// `decode_` clause that accepts values of type `t`.
    fn pattern_match_clause_decode(
        &mut self,
        t: TypeRef,
        attribute_name: Source,
        suffix: &str,
    ) -> Result<Source> {
        let graph = self.type_graph();
        let (min_value, max_value) =
            min_max_value_for_type(graph, t)?.map_or((None, None), |c| (c.0, c.1));
        let range_guard = format!(
            "{}{}",
            min_value.map_or(String::new(), |v| format!(" and value >= {}", js_number(v))),
            max_value.map_or(String::new(), |v| format!(" and value <= {}", js_number(v))),
        );
        let items_guard = |t: TypeRef| -> Result<String> {
            let (min, max) = min_max_items_for_type(graph, t)?.map_or((None, None), |c| (c.0, c.1));
            Ok(format!(
                "{}{}",
                min.map_or(String::new(), |v| format!(
                    " and length(value) >= {}",
                    js_number(v)
                )),
                max.map_or(String::new(), |v| format!(
                    " and length(value) <= {}",
                    js_number(v)
                )),
            ))
        };
        let pattern = pattern_for_type(graph, t)?;
        let (min_length, max_length) =
            min_max_length_for_type(graph, t)?.map_or((None, None), |c| (c.0, c.1));
        let length = "length(String.codepoints(value))";
        let mut constraints: Vec<String> = Vec::new();
        if let Some(min_length) = min_length {
            constraints.push(format!("{length} >= {}", js_number(min_length)));
        }
        if let Some(max_length) = max_length {
            constraints.push(format!("{length} <= {}", js_number(max_length)));
        }
        if let Some(pattern) = &pattern {
            constraints.push(format!(
                "Regex.match?(Regex.compile!(\"{}\"), value)",
                escape_double_quotes(&pattern.replace('\\', "\\\\"))
            ));
        }

        let decode = |rest: Source| sl!["def decode_", attribute_name.clone(), suffix, rest];
        Ok(match graph.kind(t)? {
            TypeKind::Any | TypeKind::Union => sl![],
            TypeKind::Null => decode("(value) when is_nil(value), do: value".into()),
            TypeKind::Bool => decode("(value) when is_boolean(value), do: value".into()),
            TypeKind::Integer => {
                decode(format!("(value) when is_integer(value){range_guard}, do: value").into())
            }
            TypeKind::Double => sl![
                "def decode_",
                attribute_name.clone(),
                suffix,
                format!("(value) when is_float(value){range_guard}, do: value\n"),
                "def decode_",
                attribute_name.clone(),
                suffix,
                format!("(value) when is_integer(value){range_guard}, do: value")
            ],
            TypeKind::String => {
                let rest = if min_length.is_none() && max_length.is_none() && pattern.is_none() {
                    "(value) when is_binary(value), do: value".to_owned()
                } else {
                    format!(
                        "(value) when is_binary(value) do\n  if {}, do: value, else: raise(ArgumentError)\nend",
                        constraints.join(" and ")
                    )
                };
                decode(rest.into())
            }
            TypeKind::Array => {
                decode(format!("(value) when is_list(value){}, do: value", items_guard(t)?).into())
            }
            TypeKind::Class => {
                let mut required_attribute_args: Vec<Source> = Vec::new();
                self.for_each_class_property(
                    t,
                    BlankLinePosition::None,
                    |_, _, json_name, p, _| {
                        if !p.is_optional {
                            required_attribute_args.push(sl![
                                "\"",
                                json_name.to_owned(),
                                "\" => _,"
                            ]);
                        }
                        Ok(())
                    },
                )?;
                sl![
                    "def decode_",
                    attribute_name,
                    suffix,
                    "(%{",
                    Source::Sequence(required_attribute_args),
                    "} = value), do: ",
                    self.name_for_named_type_with_namespace(t)?,
                    ".from_map(value)"
                ]
            }
            TypeKind::Map => decode("(value) when is_map(value), do: value".into()),
            TypeKind::Enum => sl![
                "def decode_",
                attribute_name,
                suffix,
                "(value) when is_binary(value)",
                ", do: ",
                self.name_for_named_type_with_namespace(t)?,
                ".decode(value)"
            ],
            kind => return match_type_unsupported(kind),
        })
    }

    /// `patternMatchClauseEncode(t, attributeName, suffix)`: the `encode_`
    /// clause that accepts values of type `t`.
    fn pattern_match_clause_encode(
        &mut self,
        t: TypeRef,
        attribute_name: Source,
        suffix: &str,
    ) -> Result<Source> {
        let encode = |rest: &str| sl!["def encode_", attribute_name.clone(), suffix, rest];
        Ok(match self.type_graph().kind(t)? {
            TypeKind::Any | TypeKind::Union => sl![],
            TypeKind::Null => encode("(value) when is_nil(value), do: value"),
            TypeKind::Bool => encode("(value) when is_boolean(value), do: value"),
            TypeKind::Integer => encode("(value) when is_integer(value), do: value"),
            TypeKind::Double => sl![
                "def encode_",
                attribute_name.clone(),
                suffix,
                "(value) when is_float(value), do: value\n",
                "def encode_",
                attribute_name.clone(),
                suffix,
                "(value) when is_integer(value), do: value"
            ],
            TypeKind::String => encode("(value) when is_binary(value), do: value"),
            TypeKind::Array => encode("(value) when is_list(value), do: value"),
            TypeKind::Class => {
                // The required properties are collected but unused, as in
                // TypeScript.
                self.for_each_class_property(t, BlankLinePosition::None, |_, _, _, _, _| Ok(()))?;
                let struct_pattern = if self.defined_classes.contains(&t) {
                    sl!["%", self.name_for_named_type_with_namespace(t)?, "{}"]
                } else {
                    sl![
                        "%{__struct__: ",
                        self.name_for_named_type_with_namespace(t)?,
                        "}"
                    ]
                };
                sl![
                    "def encode_",
                    attribute_name,
                    suffix,
                    "(",
                    struct_pattern,
                    " = value), do: ",
                    self.name_for_named_type_with_namespace(t)?,
                    ".to_map(value)"
                ]
            }
            TypeKind::Map => encode("(value) when is_map(value), do: value"),
            TypeKind::Enum => sl![
                "def encode_",
                attribute_name,
                suffix,
                "(value) when is_atom(value)",
                ", do: ",
                self.name_for_named_type_with_namespace(t)?,
                ".encode(value)"
            ],
            kind => return match_type_unsupported(kind),
        })
    }

    /// `sortAndFilterPatternMatchTypes(types)`: no unions; classes first,
    /// then booleans, enums, other primitives and the rest (a stable sort).
    fn sort_and_filter_pattern_match_types(&self, types: &[TypeRef]) -> Result<Vec<TypeRef>> {
        let graph = self.type_graph();
        let mut ranked: Vec<(u8, TypeRef)> = Vec::with_capacity(types.len());
        for &t in types {
            let kind = graph.kind(t)?;
            if kind != TypeKind::Union {
                ranked.push((pattern_match_rank(kind), t));
            }
        }
        ranked.sort_by_key(|&(rank, _)| rank);
        Ok(ranked.into_iter().map(|(_, t)| t).collect())
    }

    /// `emitPatternMatches(types, name, parentName, suffix, optional)`: the
    /// `decode_` and `encode_` clauses for a property (or element) that
    /// may have any of `types`.
    fn emit_pattern_matches(
        &mut self,
        types: &[TypeRef],
        name: Source,
        parent_name: Source,
        suffix: &str,
        optional: bool,
    ) -> Result<()> {
        self.ensure_blank_line();

        let mut types_to_match = self.sort_and_filter_pattern_match_types(types)?;
        if types_to_match.is_empty() {
            return Ok(());
        }

        let graph = self.type_graph();
        let has_kind = |types: &[TypeRef], kind: TypeKind| -> Result<bool> {
            for &t in types {
                if graph.kind(t)? == kind {
                    return Ok(true);
                }
            }
            Ok(false)
        };
        if has_kind(&types_to_match, TypeKind::Double)? {
            let mut kept = Vec::with_capacity(types_to_match.len());
            for t in types_to_match {
                if graph.kind(t)? != TypeKind::Integer {
                    kept.push(t);
                }
            }
            types_to_match = kept;
        }
        let has_null = has_kind(&types_to_match, TypeKind::Null)?;

        for &t in &types_to_match {
            let clause = self.pattern_match_clause_decode(t, name.clone(), suffix)?;
            self.emit_line(clause);
        }

        if optional && !has_null {
            self.emit_line_parts(vec![
                "def decode_".into(),
                name.clone(),
                suffix.into(),
                "(value) when is_nil(value), do: value".into(),
            ]);
        }

        self.emit_line_parts(vec![
            "def decode_".into(),
            name.clone(),
            suffix.into(),
            "(_), do: {:error, \"Unexpected type when decoding ".into(),
            parent_name.clone(),
            ".".into(),
            name.clone(),
            "\"}".into(),
        ]);

        self.ensure_blank_line();

        for &t in &types_to_match {
            let clause = self.pattern_match_clause_encode(t, name.clone(), suffix)?;
            self.emit_line(clause);
        }

        if optional && !has_null {
            self.emit_line_parts(vec![
                "def encode_".into(),
                name.clone(),
                suffix.into(),
                "(value) when is_nil(value), do: value".into(),
            ]);
        }

        self.emit_line_parts(vec![
            "def encode_".into(),
            name.clone(),
            suffix.into(),
            "(_), do: {:error, \"Unexpected type when encoding ".into(),
            parent_name,
            ".".into(),
            name,
            "\"}".into(),
        ]);

        self.ensure_blank_line();
        Ok(())
    }

    /// `nameOfTransformFunction(t, name, encode, prefix)`: the function that
    /// decodes (or encodes) a value of type `t`.
    fn name_of_transform_function(
        &self,
        t: TypeRef,
        name: Source,
        encode: bool,
        prefix: &str,
    ) -> Result<Source> {
        // Endless on a cycle through a nullable union (V8 overflows its stack).
        guard(|| {
            let mode = if encode { "encode" } else { "decode" };
            let ty = self.type_graph().type_at(t)?;
            Ok(match ty.kind() {
                TypeKind::Any | TypeKind::Map => sl![],
                TypeKind::Null
                | TypeKind::Bool
                | TypeKind::Integer
                | TypeKind::Double
                | TypeKind::String
                | TypeKind::Union => sl![format!("{mode}_"), name, prefix],
                TypeKind::Array => sl![
                    "(fn value -> Enum.map(value, &",
                    self.name_of_transform_function(ty.items()?, name, encode, "")?,
                    "/1) end)."
                ],
                TypeKind::Class => sl![
                    self.name_for_named_type_with_namespace(t)?,
                    if encode { ".to_map" } else { ".from_map" }
                ],
                TypeKind::Enum => sl![
                    self.name_for_named_type_with_namespace(t)?,
                    format!(".{mode}")
                ],
                kind => return match_type_unsupported(kind),
            })
        })
    }

    /// Whether every child of union `u` is primitive.
    fn all_children_primitive(&self, u: TypeRef) -> Result<bool> {
        let graph = self.type_graph();
        for c in graph.children(u)? {
            if !graph.type_at(c)?.is_primitive() {
                return Ok(false);
            }
        }
        Ok(true)
    }

    /// `fromDynamic(t, jsonName, name, optional, allowNull)`: reads property
    /// `jsonName` of map `m` as `t`.
    #[allow(clippy::wrong_self_convention)] // named after TypeScript's `fromDynamic`
    fn from_dynamic(
        &self,
        t: TypeRef,
        json_name: &str,
        name: Name,
        optional: bool,
        allow_null: bool,
    ) -> Result<Source> {
        // Endless on a cycle through a nullable union (V8 overflows its stack).
        guard(|| {
            let json_name = json_name.replace('#', "\\u{23}");
            let primitive = sl!["m[\"", json_name.clone(), "\"]"];
            let checked = sl!["decode_", name, "(", primitive.clone(), ")"];
            let optional_checked = if allow_null {
                sl![primitive.clone(), " && ", checked.clone()]
            } else {
                sl![
                    "(if Map.has_key?(m, \"",
                    json_name.clone(),
                    "\"), do: ",
                    checked.clone(),
                    ")"
                ]
            };

            let graph = self.type_graph();
            let ty = graph.type_at(t)?;
            Ok(match ty.kind() {
                TypeKind::Any => primitive,
                TypeKind::Null | TypeKind::Bool => {
                    if optional {
                        primitive
                    } else {
                        checked
                    }
                }
                TypeKind::Integer | TypeKind::Double | TypeKind::String => {
                    if optional {
                        optional_checked
                    } else {
                        checked
                    }
                }
                TypeKind::Array => {
                    let array_element = ty.items()?;
                    let element = graph.type_at(array_element)?;
                    if element.is_array() || element.is_primitive() || element.is_map() {
                        return Ok(if optional { primitive } else { checked });
                    }

                    let transform = self.name_of_transform_function(
                        array_element,
                        name.into(),
                        false,
                        "_element",
                    )?;
                    if optional {
                        sl![
                            "m",
                            "[\"",
                            json_name.clone(),
                            "\"] && Enum.map(m[\"",
                            json_name,
                            "\"], &",
                            transform,
                            "/1)"
                        ]
                    } else {
                        sl!["Enum.map(m[\"", json_name, "\"], &", transform, "/1)"]
                    }
                }
                TypeKind::Class => sl![
                    if optional {
                        sl![primitive.clone(), " && "]
                    } else {
                        Source::from("")
                    },
                    self.name_for_named_type_with_namespace(t)?,
                    ".from_map(",
                    primitive,
                    ")"
                ],
                TypeKind::Map => {
                    let values = ty.map_values()?;
                    let values_ty = graph.type_at(values)?;
                    match values_ty.kind() {
                        TypeKind::Any => sl![primitive],
                        TypeKind::Union => sl![
                            "m[\"",
                            json_name,
                            "\"]\n|> Map.new(fn {key, value} -> {key, ",
                            self.name_of_transform_function(values, name.into(), false, "")?,
                            "_value(value)} end)"
                        ],
                        kind if kind == TypeKind::Enum
                            || kind == TypeKind::Class
                            || (kind == TypeKind::Array
                                && graph.kind(values_ty.items()?)? == TypeKind::Class)
                            || (values_ty.is_primitive() && !optional) =>
                        {
                            sl![
                                "m[\"",
                                json_name,
                                "\"]\n|> Map.new(fn {key, value} -> {key, ",
                                self.name_of_transform_function(
                                    values,
                                    name.into(),
                                    false,
                                    "_value"
                                )?,
                                "(value)} end)"
                            ]
                        }
                        _ => sl![primitive],
                    }
                }
                TypeKind::Enum => sl![
                    if optional {
                        sl![primitive.clone(), " && "]
                    } else {
                        Source::from("")
                    },
                    self.name_of_transform_function(t, name.into(), false, "")?,
                    "(",
                    primitive,
                    ")"
                ],
                TypeKind::Union => {
                    if self.all_children_primitive(t)? {
                        return Ok(if optional {
                            sl!["m[\"", json_name, "\"]"]
                        } else {
                            sl!["Map.fetch!(m, \"", json_name, "\")"]
                        });
                    }

                    if let Some(nullable) = nullable_from_union(graph, t)? {
                        if graph.kind(nullable)? == TypeKind::Class {
                            return self.from_dynamic(nullable, &json_name, name, true, true);
                        }

                        if graph.children(nullable)?.len() < 2 {
                            return self.from_dynamic(nullable, &json_name, name, true, true);
                        }

                        return Ok(sl![
                            "m[\"",
                            json_name.clone(),
                            "\"] && decode_",
                            name,
                            "(m[\"",
                            json_name,
                            "\"])"
                        ]);
                    }

                    sl!["decode_", name, "(m[\"", json_name, "\"])"]
                }
                kind => return match_type_unsupported(kind),
            })
        })
    }

    /// `toDynamic(t, e, optional)`: writes property `e` of `struct` as JSON.
    fn to_dynamic(&self, t: TypeRef, e: Name, optional: bool) -> Result<Source> {
        // Endless on a cycle through a nullable union (V8 overflows its stack).
        guard(|| {
            let expression = sl!["struct.", e];
            let graph = self.type_graph();
            let ty = graph.type_at(t)?;
            Ok(match ty.kind() {
                TypeKind::Any
                | TypeKind::Null
                | TypeKind::Bool
                | TypeKind::Integer
                | TypeKind::Double
                | TypeKind::String => expression,
                TypeKind::Array => {
                    let array_element = ty.items()?;
                    let element = graph.type_at(array_element)?;
                    if element.is_array() || element.is_primitive() || element.is_map() {
                        return Ok(expression);
                    }

                    // The same whether `optional` or not.
                    sl![
                        "struct.",
                        e,
                        " && Enum.map(struct.",
                        e,
                        ", &",
                        self.name_of_transform_function(array_element, e.into(), true, "_element")?,
                        "/1)"
                    ]
                }
                TypeKind::Class => sl![
                    if optional {
                        sl!["struct.", e, " && "]
                    } else {
                        Source::from("")
                    },
                    self.name_for_named_type_with_namespace(t)?,
                    ".to_map(",
                    "struct.",
                    e,
                    ")"
                ],
                TypeKind::Map => {
                    let values = ty.map_values()?;
                    let values_ty = graph.type_at(values)?;
                    match values_ty.kind() {
                        kind if kind == TypeKind::Any || values_ty.is_primitive() => {
                            sl![expression]
                        }
                        TypeKind::Union => sl![
                            "struct.",
                            e,
                            "\n|> Map.new(fn {key, value} -> {key, ",
                            self.name_of_transform_function(values, e.into(), true, "")?,
                            "_value(value)} end)"
                        ],
                        kind if kind == TypeKind::Enum
                            || kind == TypeKind::Class
                            || (kind == TypeKind::Array
                                && graph.kind(values_ty.items()?)? == TypeKind::Class) =>
                        {
                            sl![
                                "struct.",
                                e,
                                "\n|> Map.new(fn {key, value} -> {key, ",
                                self.name_of_transform_function(values, e.into(), true, "")?,
                                "(value)} end)"
                            ]
                        }
                        _ => sl![expression],
                    }
                }
                TypeKind::Enum => sl![
                    if optional {
                        sl!["struct.", e, " && "]
                    } else {
                        Source::from("")
                    },
                    self.name_for_named_type_with_namespace(t)?,
                    ".encode(struct.",
                    e,
                    ")"
                ],
                TypeKind::Union => {
                    if self.all_children_primitive(t)? {
                        return Ok(sl!["struct.", e]);
                    }

                    if let Some(nullable) = nullable_from_union(graph, t)? {
                        if graph.kind(nullable)? == TypeKind::Class {
                            return self.to_dynamic(nullable, e, true);
                        }

                        if graph.children(nullable)?.len() < 2 {
                            return self.to_dynamic(nullable, e, true);
                        }

                        return Ok(sl!["struct.", e, " && encode_", e, "(struct.", e, ")"]);
                    }

                    sl!["encode_", e, "(struct.", e, ")"]
                }
                kind => return match_type_unsupported(kind),
            })
        })
    }

    /// `emitBlock(source, emit)`: `source`, the indented body and `end`.
    fn emit_block(
        &mut self,
        source: impl Into<Source>,
        emit: impl FnOnce(&mut Self) -> Result<()>,
    ) -> Result<()> {
        self.emit_line(source);
        self.indent(emit)?;
        self.emit_line("end");
        Ok(())
    }

    /// The `decode_`/`encode_` clauses `emitModule` emits for one property.
    fn emit_property_pattern_matches(
        &mut self,
        c: TypeRef,
        name: Name,
        p: &ClassProperty,
    ) -> Result<()> {
        let parent_name = self.name_for_named_type_with_namespace(c)?;
        let graph = self.type_graph();
        let t = p.type_ref;
        let ty = graph.type_at(t)?;
        let kind = ty.kind();
        if (ty.is_primitive() || kind == TypeKind::Array)
            && kind != TypeKind::Any
            && (!p.is_optional
                || matches!(
                    kind,
                    TypeKind::Integer | TypeKind::Double | TypeKind::String
                ))
        {
            self.emit_pattern_matches(&[t], name.into(), parent_name.clone(), "", false)?;
        }
        match kind {
            TypeKind::Union => {
                if self.all_children_primitive(t)? {
                    return Ok(());
                }
                let union_types: Vec<TypeRef> = graph.children(t)?.into_iter().collect();

                let mut union_types_non_null: Vec<TypeRef> = Vec::new();
                for &u in &union_types {
                    if graph.kind(u)? != TypeKind::Null {
                        union_types_non_null.push(u);
                    }
                }
                if let [only] = union_types_non_null[..] {
                    let mut suffix = "";
                    let mut item_types: Vec<TypeRef> = Vec::new();
                    match graph.kind(only)? {
                        TypeKind::Array => {
                            suffix = "_element";
                            item_types = graph.children(only)?.into_iter().collect();
                        }
                        TypeKind::Map => {
                            suffix = "_value";
                            item_types = graph.children(only)?.into_iter().collect();
                        }
                        _ => {}
                    }

                    if let [single] = item_types[..] {
                        if graph.kind(single)? == TypeKind::Union {
                            item_types = graph.children(single)?.into_iter().collect();
                        }
                    }

                    let parent_name = self.name_for_named_type_with_namespace(c)?;
                    self.emit_pattern_matches(
                        &item_types,
                        name.into(),
                        parent_name,
                        suffix,
                        p.is_optional,
                    )
                } else {
                    let parent_name = self.name_for_named_type_with_namespace(c)?;
                    self.emit_pattern_matches(
                        &union_types,
                        name.into(),
                        parent_name,
                        "",
                        p.is_optional,
                    )
                }
            }
            TypeKind::Array => {
                let items = ty.items()?;
                if graph.kind(items)? == TypeKind::Union {
                    let types_in_union: Vec<TypeRef> = graph.children(items)?.into_iter().collect();
                    let parent_name = self.name_for_named_type_with_namespace(c)?;
                    self.emit_pattern_matches(
                        &types_in_union,
                        name.into(),
                        parent_name,
                        "_element",
                        false,
                    )?;
                }
                Ok(())
            }
            TypeKind::Map => {
                let value = ty.map_values()?;
                let value_ty = graph.type_at(value)?;
                if value_ty.is_primitive() && value_ty.kind() != TypeKind::Any {
                    self.emit_pattern_matches(&[value], name.into(), parent_name, "_value", false)?;
                } else if value_ty.is_union() {
                    let types_in_union: Vec<TypeRef> = graph.children(value)?.into_iter().collect();
                    let parent_name = self.name_for_named_type_with_namespace(c)?;
                    self.emit_pattern_matches(
                        &types_in_union,
                        name.into(),
                        parent_name,
                        "_value",
                        false,
                    )?;
                }
                Ok(())
            }
            _ => Ok(()),
        }
    }

    /// `emitModule(c, moduleName)`: the module of class `c`.
    fn emit_module(&mut self, c: TypeRef, module_name: Name) -> Result<()> {
        let module = self.name_with_namespace(module_name);
        self.emit_block(sl!["defmodule ", module.clone(), " do"], |r| {
            let struct_description = r.description_for_type(c)?.unwrap_or_default();
            let mut attribute_descriptions: Vec<Source> = Vec::new();
            r.for_each_class_property(c, BlankLinePosition::None, |r, name, json_name, _, _| {
                if let Some(description) = r.description_for_class_property(c, json_name)? {
                    let lines: Vec<Source> = description.into_iter().map(Source::from).collect();
                    attribute_descriptions.push(sl!["- `:", name, "` - ", Source::Sequence(lines)]);
                }
                Ok(())
            })?;
            if !struct_description.is_empty() || !attribute_descriptions.is_empty() {
                let mut lines: Vec<Source> =
                    struct_description.into_iter().map(Source::from).collect();
                lines.extend(attribute_descriptions);
                r.emit_description(Some(lines))?;
                r.ensure_blank_line();
            }

            let mut required_attributes: Vec<Source> = Vec::new();
            r.for_each_class_property(c, BlankLinePosition::None, |_, name, _, p, _| {
                if !p.is_optional {
                    let separator = if required_attributes.is_empty() {
                        ":"
                    } else {
                        ", :"
                    };
                    required_attributes.push(sl![separator, name]);
                }
                Ok(())
            })?;
            if !required_attributes.is_empty() {
                r.emit_line(sl![
                    "@enforce_keys [",
                    Source::Sequence(required_attributes),
                    "]"
                ]);
            }

            let mut attribute_names: Vec<Source> = Vec::new();
            r.for_each_class_property(c, BlankLinePosition::None, |_, name, _, _, _| {
                let separator = if attribute_names.is_empty() {
                    ":"
                } else {
                    ", :"
                };
                attribute_names.push(sl![separator, name]);
                Ok(())
            })?;

            r.emit_line(sl!["defstruct [", Source::Sequence(attribute_names), "]"]);
            r.defined_classes.insert(c);
            r.ensure_blank_line();

            let mut type_definition_table: Vec<Vec<Source>> =
                vec![vec![sl!["@type "], sl!["t :: %__MODULE__{"]]];
            let mut count = r.type_graph().type_at(c)?.properties()?.len();
            r.for_each_class_property(c, BlankLinePosition::None, |r, name, _, p, _| {
                count = count.wrapping_sub(1);
                let last = count == 0;
                let elixir_type = r.elixir_type(p.type_ref, false)?;
                type_definition_table.push(vec![
                    sl![],
                    sl![
                        "  ",
                        name,
                        ": ",
                        elixir_type,
                        if p.is_optional { " | nil" } else { "" },
                        if last { "" } else { "," }
                    ],
                ]);
                Ok(())
            })?;
            type_definition_table.push(vec![sl![], sl!["}"]]);
            r.emit_table(type_definition_table);
            if r.options.just_types {
                return Ok(());
            }

            r.for_each_class_property(c, BlankLinePosition::None, |r, name, _, p, _| {
                r.emit_property_pattern_matches(c, name, &p)
            })?;
            let prop_count = r.property_count(c)?;
            let is_empty = prop_count == 0;
            r.ensure_blank_line();
            let from_map = format!(
                "def from_map(m){} do",
                if is_empty { " when is_map(m)" } else { "" }
            );
            r.emit_block(sl![from_map], |r| {
                r.emit_line_parts(vec!["%".into(), module.clone(), "{".into()]);
                r.indent(|r| {
                    r.for_each_class_property(
                        c,
                        BlankLinePosition::None,
                        |r, name, json_name, p, _| {
                            let json_name = escape_new_lines(&escape_double_quotes(json_name));
                            let allow_null = is_nullable(r.type_graph(), p.type_ref)?;
                            let expression = r.from_dynamic(
                                p.type_ref,
                                &json_name,
                                name,
                                p.is_optional,
                                allow_null,
                            )?;
                            r.emit_line_parts(vec![
                                name.into(),
                                ": ".into(),
                                expression,
                                ",".into(),
                            ]);
                            Ok(())
                        },
                    )
                })?;
                r.emit_line("}");
                Ok(())
            })?;
            r.ensure_blank_line();
            r.emit_block("def from_json(json) do", |r| {
                r.emit_multiline(FROM_JSON_BODY)
            })?;
            r.ensure_blank_line();
            let to_map = format!("def to_map({}struct) do", if is_empty { "_" } else { "" });
            r.emit_block(sl![to_map], |r| {
                r.emit_line("%{");
                r.indent(|r| {
                    r.for_each_class_property(
                        c,
                        BlankLinePosition::None,
                        |r, name, json_name, p, _| {
                            let expression = r.to_dynamic(p.type_ref, name, p.is_optional)?;
                            r.emit_line(sl![
                                sl![format!("\"{}\"", string_escape(json_name))],
                                sl![" => ", expression, ","]
                            ]);
                            Ok(())
                        },
                    )
                })?;
                r.emit_line("}");
                Ok(())
            })?;
            r.ensure_blank_line();
            r.emit_block("def to_json(struct) do", |r| r.emit_multiline(TO_JSON_BODY))
        })
    }

    /// `emitEnum(e, enumName)`: the module of enum `e`.
    fn emit_enum(&mut self, e: TypeRef, enum_name: Name) -> Result<()> {
        let module = self.name_with_namespace(enum_name);
        self.emit_block(sl!["defmodule ", module, " do"], |r| {
            let description = r.description_for_type(e)?;
            r.emit_description(description)?;
            r.emit_line("@valid_enum_members [");
            r.indent(|r| {
                r.for_each_enum_case(e, BlankLinePosition::None, |r, _, json, _| {
                    if is_valid_atom(json) {
                        r.emit_line_parts(vec![":".into(), json.into(), ",".into()]);
                    } else {
                        r.emit_line_parts(vec![
                            ":".into(),
                            format!("\"{json}\"").into(),
                            ",".into(),
                        ]);
                    }
                    Ok(())
                })
            })?;

            r.emit_line("]");

            r.ensure_blank_line();

            r.emit_multiline(ENUM_FUNCTIONS)
        })
    }

    /// The module of a top-level that is a union or not a named type.
    fn emit_top_level_module(&mut self, top_level: TypeRef, name: Name) -> Result<()> {
        let graph = self.type_graph();
        let top_ty = graph.type_at(top_level)?;
        let is_top_level_array = top_ty.kind() == TypeKind::Array;

        let module = self.name_with_namespace(name);
        self.emit_block(sl!["defmodule ", module, " do"], |r| {
            let description = r.description_for_type(top_level)?.unwrap_or_default();
            if !description.is_empty() {
                r.emit_description(Some(description))?;
                r.ensure_blank_line();
            }

            if is_top_level_array {
                let array_element = top_ty.items()?;
                let element_ty = graph.type_at(array_element)?;
                let element_module = if element_ty.is_primitive() {
                    Source::from("")
                } else {
                    r.name_for_named_type_with_namespace(array_element)?
                };

                let mut is_union = false;

                if element_ty.is_union() {
                    let children: Vec<TypeRef> =
                        graph.children(array_element)?.into_iter().collect();
                    r.emit_pattern_matches(&children, "element".into(), name.into(), "", false)?;
                    is_union = true;
                } else if element_ty.is_primitive() {
                    r.emit_pattern_matches(
                        &[array_element],
                        "element".into(),
                        name.into(),
                        "",
                        false,
                    )?;
                    is_union = true;
                }

                let element_module_for_decode = element_module.clone();
                r.emit_block("def from_json(json) do", |r| {
                    r.emit_line("json");
                    r.emit_line("|> Jason.decode!()");
                    r.emit_line_parts(vec![
                        "|> Enum.map(&".into(),
                        if is_union {
                            sl!["decode_element/1)"]
                        } else {
                            sl![element_module_for_decode, ".from_map/1)"]
                        },
                    ]);
                    Ok(())
                })?;

                r.ensure_blank_line();

                r.emit_block("def to_json(list) do", |r| {
                    r.emit_line_parts(vec![
                        "Enum.map(list, &".into(),
                        if is_union {
                            sl!["encode_element/1)"]
                        } else {
                            sl![element_module, ".to_map/1)"]
                        },
                    ]);
                    r.emit_line("|> Jason.encode!()");
                    Ok(())
                })
            } else {
                if top_ty.is_union() {
                    let children: Vec<TypeRef> = graph.children(top_level)?.into_iter().collect();
                    r.emit_pattern_matches(&children, "value".into(), name.into(), "", false)?;
                }
                if top_ty.is_map() {
                    let clause = r.pattern_match_clause_decode(top_level, "value".into(), "")?;
                    r.emit_line(clause);
                    r.ensure_blank_line();
                }

                r.emit_block("def from_json(json) do", |r| {
                    r.emit_line("json");
                    r.emit_line("|> Jason.decode!()");
                    if top_ty.is_map() || top_ty.is_union() {
                        r.emit_line("|> decode_value()");
                    }
                    Ok(())
                })?;

                r.ensure_blank_line();

                r.emit_block("def to_json(data) do", |r| {
                    if top_ty.is_union() {
                        r.emit_line("data |> encode_value()");
                        r.emit_line("|> Jason.encode!()");
                    } else {
                        r.emit_line("Jason.encode!(data)");
                    }
                    Ok(())
                })
            }
        })
    }
}

impl<'a> ConvenienceRenderer<'a> for ElixirRenderer<'a> {
    fn core(&self) -> &ConvenienceRendererCore<'a> {
        &self.core
    }

    fn core_mut(&mut self) -> &mut ConvenienceRendererCore<'a> {
        &mut self.core
    }

    fn comment_line_start(&self) -> &'static str {
        "# "
    }

    fn needs_type_declaration_before_use(&self) -> bool {
        true
    }

    fn can_be_forward_declared(&self, t: TypeRef) -> Result<bool> {
        Ok(self.type_graph().kind(t)? == TypeKind::Class)
    }

    fn forbidden_names_for_global_namespace(&mut self) -> Result<Vec<String>> {
        let mut names: Vec<String> = FORBIDDEN_MODULE_NAMES
            .iter()
            .map(|&n| n.to_owned())
            .collect();
        names.extend(RESERVED_WORDS.iter().map(|w| capitalize_first_letter(w)));
        Ok(names)
    }

    fn forbidden_for_object_properties(
        &mut self,
        _c: TypeRef,
        _class_name: Name,
    ) -> Result<ForbiddenWordsInfo> {
        Ok(ForbiddenWordsInfo {
            names: RESERVED_WORDS.iter().map(|&w| w.into()).collect(),
            include_global_forbidden: true,
        })
    }

    fn make_named_type_namer(&mut self) -> Namer {
        Namer::new(
            "types",
            |n| simple_name_style(n, true),
            Vec::<String>::new(),
            false,
        )
    }

    fn namer_for_object_property(
        &mut self,
        _o: TypeRef,
        _p: &ClassProperty,
    ) -> Result<Option<Namer>> {
        // A new namer per call, as in TypeScript.
        Ok(Some(Namer::new(
            "properties",
            member_name_style,
            Vec::<String>::new(),
            false,
        )))
    }

    fn make_union_member_namer(&mut self) -> Option<Namer> {
        Some(Namer::new(
            "properties",
            member_name_style,
            Vec::<String>::new(),
            false,
        ))
    }

    fn make_enum_case_namer(&mut self) -> Option<Namer> {
        Some(Namer::new(
            "enum-cases",
            |n| simple_name_style(n, true),
            Vec::<String>::new(),
            false,
        ))
    }

    fn emit_description_block(&mut self, lines: &[Source]) -> Result<()> {
        self.emit_comment_lines(
            lines,
            &CommentOptions {
                first_line_start: Some("@moduledoc \"\"\"\n".to_owned()),
                line_start: Some(String::new()),
                after_comment: Some("\"\"\"".to_owned()),
                ..CommentOptions::default()
            },
        )
    }

    fn emit_source_structure(&mut self, _given_output_filename: &str) -> Result<()> {
        if let Some(leading_comments) = self.leading_comments() {
            self.emit_comments(leading_comments)?;
        } else if !self.options.just_types {
            self.emit_multiline(HEADER)?;
            self.for_each_top_level(BlankLinePosition::None, |r, _, name, _| {
                r.emit_line("#");
                let module = r.name_with_namespace(name);
                r.emit_line_parts(vec![
                    "# Decode a JSON string: ".into(),
                    module.clone(),
                    ".from_json(data)".into(),
                ]);
                r.emit_line_parts(vec![
                    "# Encode into a JSON string: ".into(),
                    module,
                    ".to_json(struct)".into(),
                ]);
                Ok(())
            })?;
        }

        self.ensure_blank_line();

        self.for_each_named_type(
            BlankLinePosition::LeadingAndInterposing,
            |r, c, n, _| r.emit_module(c, n),
            |r, e, n, _| r.emit_enum(e, n),
            // `emitUnion` emits nothing.
            |_, _, _, _| Ok(()),
        )?;

        if !self.options.just_types {
            self.for_each_top_level_where(
                BlankLinePosition::LeadingAndInterposing,
                |r, t| {
                    Ok(r.type_graph().type_at(t)?.is_union()
                        || r.named_type_to_name_for_top_level(t)?.is_none())
                },
                |r, top_level, name, _| r.emit_top_level_module(top_level, name),
            )?;
        }
        Ok(())
    }
}
